#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
手动指令注错配置示例

这个文件展示了如何配置手动指令注错。
复制这些配置到 configure.py 中即可使用。
"""

# ============================================================
# 示例 1: 对单个指令注错多次
# ============================================================
example_1 = [
    ["rbp", "", "0x4026b1", 100],  # 对该指令注错 100 次，iteration 0~99
]

# ============================================================
# 示例 2: 对多个指令分别注错
# ============================================================
example_2 = [
    ["rbp", "", "0x4026b1", 50],   # 指令 1：注错 50 次
    ["rax", "", "0x402605", 30],   # 指令 2：注错 30 次
    ["rdx", "", "0x402678", 20],   # 指令 3：注错 20 次
]

# ============================================================
# 示例 3: 从 catalog 文件选择指令
# ============================================================
# 假设你的 mov_catalog.csv 内容如下：
# rbp,,4026b1,MOV,mov eax, dword ptr [rbp-0x1c],12474
# rbp,,402605,MOV,mov eax, dword ptr [rbp-0x24],12096
# rdx,,402678,MOVSD_XMM,movsd xmm0, qword ptr [rdx+rax*8],12096

example_3 = [
    ["rbp", "", "0x4026b1", 100],  # 从 catalog 第 1 行
    ["rbp", "", "0x402605", 100],  # 从 catalog 第 2 行
    ["rdx", "", "0x402678", 100],  # 从 catalog 第 3 行
]

# ============================================================
# 示例 4: 混合使用不同注错次数
# ============================================================
example_4 = [
    ["rbp", "", "0x4026b1", 200],  # 重点关注的指令，注错 200 次
    ["rax", "", "0x402605", 50],   # 次要指令，注错 50 次
    ["rdx", "", "0x402678"],       # 只验证一次，注错 1 次
]

# ============================================================
# 示例 5: 针对 fdtd-2d 程序的实际配置
# ============================================================
# 基于 fdtd-2d 的 mov_catalog.csv 选择的指令
example_fdtd_2d = [
    ["rbp", "", "0x1180", 100],    # 程序入口附近的 mov 指令
    ["rbp", "", "0x11a0", 100],    # 核心计算循环中的 mov 指令
    ["rax", "", "0x1200", 100],    # 数据传输指令
]

# ============================================================
# 使用方法
# ============================================================
# 1. 选择上面的一个示例（或自定义）
# 2. 在 configure.py 中设置：
#
#    use_manual_instructions = True
#    manual_instructions = example_1  # 或其他示例
#
# 3. 运行 letgo_wrapper.py

print("手动指令注错配置示例")
print("=" * 60)
print("\n示例 1: 对单个指令注错多次")
print(f"  配置: {example_1}")
print(f"  总注错次数: {sum(x[3] if len(x) > 3 else 1 for x in example_1)}")

print("\n示例 2: 对多个指令分别注错")
print(f"  配置: {example_2}")
print(f"  总注错次数: {sum(x[3] if len(x) > 3 else 1 for x in example_2)}")

print("\n示例 3: 从 catalog 文件选择指令")
print(f"  配置: {example_3}")
print(f"  总注错次数: {sum(x[3] if len(x) > 3 else 1 for x in example_3)}")

print("\n示例 4: 混合使用不同注错次数")
print(f"  配置: {example_4}")
print(f"  总注错次数: {sum(x[3] if len(x) > 3 else 1 for x in example_4)}")

print("\n示例 5: 针对 fdtd-2d 程序")
print(f"  配置: {example_fdtd_2d}")
print(f"  总注错次数: {sum(x[3] if len(x) > 3 else 1 for x in example_fdtd_2d)}")

print("\n" + "=" * 60)
